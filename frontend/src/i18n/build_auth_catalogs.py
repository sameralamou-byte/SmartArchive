CATALOGS = {
    "en": EN,
    "de": DE,
    "ar": AR,
    "es": ES,
    "fr": FR,
    "it": IT,
    "nl": NL,
    "pl": PL,
    "pt": PT,
    "ru": RU,
    "tr": TR,
    "uk": UK,
}


def main() -> None:
    out = Path(__file__).resolve().parent / "auth"
    out.mkdir(parents=True, exist_ok=True)
    keys = list(EN)
    for code, catalog in CATALOGS.items():
        missing = [key for key in keys if key not in catalog]
        extra = [key for key in catalog if key not in EN]
        empty = [key for key, value in catalog.items() if not str(value).strip()]
        if missing or extra or empty:
            raise SystemExit(f"{code}: missing={missing} extra={extra} empty={empty}")
        (out / f"{code}.json").write_text(
            json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    print(f"wrote {len(CATALOGS)} catalogs x {len(keys)} keys")


if __name__ == "__main__":
    main()
